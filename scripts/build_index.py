#!/usr/bin/env python3
"""public/ 폴더를 읽어 index.html(자동 목차)을 만든다.

- HTML 파일: <title>, 설명(meta description 또는 첫 문단), h2 소제목을 뽑아
  각 소제목으로 바로 가는 링크 목차를 만든다.
- 그 밖의 파일: 이름과 크기만 표시한다.
- 하위 폴더도 재귀적으로 읽고, index.html이 없는 폴더마다 같은 목차를 만든다.
- 직접 만든 index.html이 있는 폴더는 건드리지 않는다.

사용법: python3 scripts/build_index.py public
"""
import html
import os
import sys
from datetime import datetime, timezone, timedelta
from html.parser import HTMLParser

GENERATED_MARK = "<!-- auto-generated by build_index.py -->"
CONTAINERS = {"section", "article", "main", "nav", "header", "aside", "div"}


class PageInfo(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.description = ""
        self.first_p = ""
        self.headings = []  # (anchor id, text)
        self._stack = []  # 열린 컨테이너 태그와 id: [(tag, id)]
        self._cap = None  # 'title' | 'h2' | 'p'
        self._buf = []
        self._h2_id = None
        self._skip = 0  # inside <script>/<style>

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("script", "style"):
            self._skip += 1
            return
        if tag in CONTAINERS:
            self._stack.append((tag, a.get("id")))
        if tag == "meta" and a.get("name", "").lower() == "description":
            self.description = a.get("content", "").strip()
        elif tag == "title" and not self.title:
            self._cap, self._buf = "title", []
        elif tag == "h2" and self._cap is None and not self._in("nav"):
            self._cap, self._buf = "h2", []
            # 소제목 자체의 id, 없으면 감싸는 섹션의 id로 연결한다
            self._h2_id = a.get("id") or next(
                (i for _, i in reversed(self._stack) if i), None)
        elif tag == "p" and self._cap is None and not self.first_p:
            self._cap, self._buf = "p", []

    def _in(self, tag):
        return any(t == tag for t, _ in self._stack)

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self._skip = max(0, self._skip - 1)
            return
        if tag in CONTAINERS:
            for k in range(len(self._stack) - 1, -1, -1):
                if self._stack[k][0] == tag:
                    del self._stack[k:]
                    break
        if self._cap and tag == self._cap:
            text = " ".join("".join(self._buf).split())
            if self._cap == "title":
                self.title = text
            elif self._cap == "h2" and text:
                self.headings.append((self._h2_id, text))
            elif self._cap == "p":
                self.first_p = text
            self._cap = None

    def handle_data(self, data):
        if self._cap and not self._skip:
            self._buf.append(data)


def read_page(path):
    p = PageInfo()
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            p.feed(f.read())
    except Exception:
        pass
    desc = p.description or p.first_p
    if len(desc) > 140:
        desc = desc[:139].rstrip() + "…"
    return p.title, desc, p.headings


def human_size(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def is_generated(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return GENERATED_MARK in f.read(300)
    except FileNotFoundError:
        return True


def visible(name):
    return not name.startswith(".")


def collect(base):
    """base 아래를 재귀적으로 훑어 [(상대 폴더, [항목...])] 를 돌려준다."""
    groups = []
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if visible(d))
        rel_dir = os.path.relpath(dirpath, base)
        items = []
        for name in sorted(filenames):
            if not visible(name):
                continue
            full = os.path.join(dirpath, name)
            if name == "index.html" and is_generated(full):
                continue
            href = os.path.relpath(full, base).replace(os.sep, "/")
            item = {"name": name, "href": href, "size": os.path.getsize(full)}
            if name.lower().endswith((".html", ".htm")):
                item["title"], item["desc"], item["headings"] = read_page(full)
            items.append(item)
        if items:
            groups.append(("" if rel_dir == "." else rel_dir.replace(os.sep, "/"), items))
    return groups


