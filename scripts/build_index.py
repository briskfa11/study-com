def render(title, groups, up_link):
    e = html.escape
    kst = datetime.now(timezone(timedelta(hours=9))).strftime("%Y-%m-%d %H:%M")
    pages = sum(1 for _, items in groups for i in items if "title" in i)
    files = sum(len(items) for _, items in groups)
    out = [
        "<!doctype html>", GENERATED_MARK,
        '<html lang="ko"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>{e(title)}</title><style>{CSS}</style></head><body><div class=\"wrap\">",
        f"<header><h1>{e(title)}</h1><p>자료 {pages}개 · 파일 {files}개</p></header>",
    ]
    if up_link:
        out.append('<p><a href="../" style="color:var(--accent)">← 상위 폴더</a></p>')

    pages_list = [(d, i) for d, items in groups for i in items if "title" in i]
    if len(pages_list) > 1:
        out.append('<nav class="toc"><b>목차</b>')
        for n, (_, i) in enumerate(pages_list, 1):
            out.append(f'<a href="#doc-{n}">{e(i["title"] or i["name"])}</a>')
        out.append("</nav>")

    n = 0
    for folder, items in groups:
        if folder or len(groups) > 1:
            out.append(f'<h2 class="folder">/{e(folder)}</h2>')
        others = [i for i in items if "title" not in i]
        for i in items:
            if "title" not in i:
                continue
            n += 1
            href = e(i["href"])
            out.append(f'<article class="card" id="doc-{n}">')
            out.append(f'<h3><a href="{href}">{e(i["title"] or i["name"])}</a></h3>')
            out.append(f'<div class="meta">{e(i["href"])} · {human_size(i["size"])}</div>')
            if i["desc"]:
                out.append(f'<p class="desc">{e(i["desc"])}</p>')
            if i["headings"]:
                out.append('<ol class="sec">')
                for anchor, text in i["headings"]:
                    link = f"{href}#{e(anchor)}" if anchor else href
                    out.append(f'<li><a href="{link}">{e(text)}</a></li>')
                out.append("</ol>")
            out.append("</article>")
        if others:
            out.append('<div class="card"><ul class="files">')
            for i in others:
                out.append(f'<li><a href="{e(i["href"])}">{e(i["name"])}</a>'
                           f'<span class="meta">{human_size(i["size"])}</span></li>')
            out.append("</ul></div>")

    if not groups:
        out.append("<p>아직 파일이 없습니다.</p>")
    out.append(f"<footer>자동 생성 목차 · {kst} KST</footer></div></body></html>")
    return "\n".join(out)


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "public"
    site_title = os.environ.get("SITE_TITLE", "학습 자료")
    for dirpath, dirnames, _ in os.walk(root):
        dirnames[:] = [d for d in dirnames if visible(d)]
        index = os.path.join(dirpath, "index.html")
        if not is_generated(index):
            continue  # 직접 만든 index.html은 그대로 둔다
        rel = os.path.relpath(dirpath, root)
        title = site_title if rel == "." else f"{site_title} / {rel.replace(os.sep, '/')}"
        page = render(title, collect(dirpath), up_link=rel != ".")
        with open(index, "w", encoding="utf-8") as f:
            f.write(page)
        print("generated", index)


if __name__ == "__main__":
    main()
